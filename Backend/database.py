async def db_upsert_user(
    google_sub: str,
    email: str,
    name: str,
    avatar_url: str | None,
) -> dict:
    """
    Insert a new user or refresh name/avatar/email for a returning user.

    Conflict target is google_sub — stable across Google profile changes.
    user_id is never touched on update so all existing JWTs stay valid.
    RETURNING gives back the row in one query — no second lookup needed.
    """
    async with _pool.connection() as conn:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                INSERT INTO users (google_sub, email, name, avatar_url)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (google_sub) DO UPDATE
                    SET name       = EXCLUDED.name,
                        avatar_url = EXCLUDED.avatar_url,
                        email      = EXCLUDED.email
                RETURNING user_id, email, name, avatar_url
                """,
                (google_sub, email, name, avatar_url),
            )
            row = await cur.fetchone()

    return {
        "user_id":    str(row[0]),
        "email":      row[1],
        "name":       row[2],
        "avatar_url": row[3],
    }


async def db_get_user(user_id: str) -> dict | None:
    """Fetch a user by their internal user_id. Returns None if not found."""
    async with _pool.connection() as conn:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                SELECT user_id, email, name, avatar_url, created_at
                FROM users
                WHERE user_id = %s
                """,
                (user_id,),
            )
            row = await cur.fetchone()

    if row is None:
        return None
    return {
        "user_id":    str(row[0]),
        "email":      row[1],
        "name":       row[2],
        "avatar_url": row[3],
        "created_at": row[4],
    }


