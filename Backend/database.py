async def db_create_thread(thread_id: str, user_id: str) -> dict:
    """
    Insert a new thread row.
    thread_id is UUIDv7 generated by the caller — encodes creation time.
    """
    async with _pool.connection() as conn:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                INSERT INTO threads (thread_id, user_id)
                VALUES (%s, %s)
                RETURNING thread_id, user_id, updated_at
                """,
                (thread_id, user_id),
            )
            row = await cur.fetchone()

    return {
        "thread_id":  row[0],
        "user_id":    str(row[1]),
        "updated_at": row[2],
    }


async def db_get_thread(thread_id: str) -> dict | None:
    """
    Fetch a single thread by primary key.
    O(log n) — direct primary key lookup.
    """
    async with _pool.connection() as conn:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                SELECT thread_id, user_id, updated_at
                FROM threads
                WHERE thread_id = %s
                """,
                (thread_id,),
            )
            row = await cur.fetchone()

    if row is None:
        return None
    return {
        "thread_id":  row[0],
        "user_id":    str(row[1]),
        "updated_at": row[2],
    }


async def db_list_threads(user_id: str) -> list[dict]:
    """
    Return all threads for a user ordered by most recently active.
    Index-only scan via idx_threads_last_active — never touches the table.
    """
    async with _pool.connection() as conn:
        async with conn.cursor() as cur:
            await cur.execute(
                """
                SELECT thread_id, user_id, updated_at
                FROM threads
                WHERE user_id = %s
                ORDER BY updated_at DESC
                """,
                (user_id,),
            )
            rows = await cur.fetchall()

    return [
        {
            "thread_id":  r[0],
            "user_id":    str(r[1]),
            "updated_at": r[2],
        }
        for r in rows
    ]


async def db_touch_thread(thread_id: str, user_id: str) -> None:
    """
    Bump updated_at only if this thread is not already the most recent one
    for this user. If it is already first, ordering won't change — skip the write.

    Both the subquery and the outer UPDATE use indexes — O(log n) total.
    The subquery is uncorrelated so Postgres executes it once, not per row.
    One round trip, one conditional write.
    """
    async with _pool.connection() as conn:
        await conn.execute(
            """
            UPDATE threads
            SET updated_at = NOW()
            WHERE thread_id = %s
            AND thread_id != (
                SELECT thread_id FROM threads
                WHERE user_id = %s
                ORDER BY updated_at DESC
                LIMIT 1
            )
            """,
            (thread_id, user_id),
        )


async def db_delete_thread(thread_id: str) -> bool:
    """
    Delete a thread metadata row.
    Returns True if a row was deleted, False if thread was not found.

    Note: LangGraph checkpoint data lives in its own tables and is not
    deleted here — no public API for that yet.
    """
    async with _pool.connection() as conn:
        async with conn.cursor() as cur:
            await cur.execute(
                "DELETE FROM threads WHERE thread_id = %s RETURNING thread_id",
                (thread_id,),
            )
            row = await cur.fetchone()
    return row is not None


