def _hash_token(raw_token: str) -> str:
    """SHA-256 hash of a raw token. Always store and compare hashes, never raw."""
    return hashlib.sha256(raw_token.encode()).hexdigest()


async def db_create_refresh_token(user_id: str, expires_at: datetime) -> str:
    """
    Generate a cryptographically random refresh token, store its hash,
    and return the raw token to be sent to the client via HttpOnly cookie.

    The raw token is never stored — only the hash. A breached DB is useless
    without the raw values.
    """
    raw_token  = secrets.token_urlsafe(64)
    token_hash = _hash_token(raw_token)

    async with _pool.connection() as conn:
        await conn.execute(
            """
            INSERT INTO refresh_tokens (token_hash, user_id, expires_at)
            VALUES (%s, %s, %s)
            """,
            (token_hash, user_id, expires_at),
        )

    return raw_token  # caller puts this in the HttpOnly cookie


async def db_rotate_refresh_token(
    raw_token: str,
    expires_at: datetime,
) -> tuple[str, str] | None:
    """
    Validate and rotate a refresh token in one operation:
      1. Hash the incoming raw token
      2. Look it up — missing means invalid or already rotated (reuse detected)
      3. Check expiry
      4. Delete the old token
      5. Insert a fresh token for the same user
      6. Return (user_id, new_raw_token)

    Returns None if the token is invalid or expired.
    Rotation means each token is single-use — reuse is detected immediately.
    """
    token_hash = _hash_token(raw_token)
    now        = datetime.now(timezone.utc)

    async with _pool.connection() as conn:
        async with conn.cursor() as cur:

            await cur.execute(
                """
                SELECT user_id, expires_at
                FROM refresh_tokens
                WHERE token_hash = %s
                """,
                (token_hash,),
            )
            row = await cur.fetchone()

            if row is None:
                return None  # not found — never existed or already rotated

            user_id      = str(row[0])
            token_expiry = row[1]

            if token_expiry.replace(tzinfo=timezone.utc) < now:
                return None  # expired

            # Delete old token
            await cur.execute(
                "DELETE FROM refresh_tokens WHERE token_hash = %s",
                (token_hash,),
            )

            # Issue new token
            new_raw   = secrets.token_urlsafe(64)
            new_hash  = _hash_token(new_raw)

            await cur.execute(
                """
                INSERT INTO refresh_tokens (token_hash, user_id, expires_at)
                VALUES (%s, %s, %s)
                """,
                (new_hash, user_id, expires_at),
            )

    return user_id, new_raw


async def db_delete_refresh_token(raw_token: str) -> None:
    """Delete a single refresh token — used on logout."""
    token_hash = _hash_token(raw_token)
    async with _pool.connection() as conn:
        await conn.execute(
            "DELETE FROM refresh_tokens WHERE token_hash = %s",
            (token_hash,),
        )


async def db_delete_all_user_tokens(user_id: str) -> None:
    """
    Revoke all sessions for a user.
    Used when suspicious activity is detected or user requests logout
    from all devices.
    """
    async with _pool.connection() as conn:
        await conn.execute(
            "DELETE FROM refresh_tokens WHERE user_id = %s",
            (user_id,),
        )