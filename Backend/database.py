"""
Database connection pool management.

Single source of truth for the async pool, LangGraph checkpointer and store,
and all application table schemas + CRUD helpers.

Tables owned here:
  - users          (identity, created on first Google login)
  - threads        (conversation metadata, one per LangGraph thread)
  - refresh_tokens (session management, rotated on every use)
"""
import hashlib
import secrets
from datetime import datetime, timezone

from psycopg_pool import AsyncConnectionPool
from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
from langgraph.store.postgres.aio import AsyncPostgresStore


_pool: AsyncConnectionPool | None = None
_checkpointer: AsyncPostgresSaver | None = None
_store: AsyncPostgresStore | None = None


# ---------------------------------------------------------------------------
# Lifecycle
# ---------------------------------------------------------------------------

async def setup_database(database_url: str) -> None:
    """
    Initialize DB pool, run LangGraph migrations, and create app tables.
    Call once on startup — before compiling the workflow graph.
    """
    global _pool, _checkpointer, _store

    _pool = AsyncConnectionPool(
        conninfo=database_url,
        open=False,
        kwargs={"autocommit": True, "prepare_threshold": 0},
    )

    _checkpointer = AsyncPostgresSaver(_pool)
    _store        = AsyncPostgresStore(_pool)

    await _pool.open()
    await _checkpointer.setup()
    await _store.setup()
    await _create_app_tables()


async def teardown_database() -> None:
    """Close DB pool. Call on shutdown."""
    global _pool
    if _pool:
        await _pool.close()


# ---------------------------------------------------------------------------
# Accessors
# ---------------------------------------------------------------------------

def get_pool() -> AsyncConnectionPool:
    if _pool is None:
        raise RuntimeError("Database not initialized")
    return _pool


def get_checkpointer() -> AsyncPostgresSaver:
    if _checkpointer is None:
        raise RuntimeError("Database not initialized")
    return _checkpointer


def get_store() -> AsyncPostgresStore:
    if _store is None:
        raise RuntimeError("Database not initialized")
    return _store


# ---------------------------------------------------------------------------
# App table migrations
# ---------------------------------------------------------------------------

async def _create_app_tables() -> None:
    """
    Create all application-owned tables in dependency order.
    users must exist before threads and refresh_tokens (FK constraint).
    """
    async with _pool.connection() as conn:

        # ── users ──────────────────────────────────────────────────────────
        # user_id    : your internal UUID, used in JWTs and across all tables
        # google_sub : Google's stable user identifier — upsert conflict target
        #              never changes even if the user changes their email
        # email      : stored for display, refreshed on every login
        # name       : refreshed on every login via upsert
        # avatar_url : Google profile picture, refreshed on every login
        # created_at : account age is useful — kept here unlike threads table
        await conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                user_id     UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
                google_sub  TEXT        UNIQUE NOT NULL,
                email       TEXT        UNIQUE NOT NULL,
                name        TEXT        NOT NULL,
                avatar_url  TEXT,
                created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # ── threads ────────────────────────────────────────────────────────
        # thread_id  : UUIDv7 generated by caller — primary key + creation time
        # user_id    : FK to users, cascade delete removes threads with the user
        # updated_at : bumped conditionally — only if not already most recent thread
        #              see db_touch_thread for the optimized conditional update
        await conn.execute("""
            CREATE TABLE IF NOT EXISTS threads (
                thread_id   TEXT        PRIMARY KEY,
                user_id     UUID        NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        # Covering index — list_threads query is index-only, never touches table rows
        # (user_id, updated_at DESC) for range scan + ordering
        # INCLUDE (thread_id) eliminates heap fetch for the SELECT
        await conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_threads_last_active
                ON threads (user_id, updated_at DESC)
                INCLUDE (thread_id)
        """)

        # ── refresh_tokens ─────────────────────────────────────────────────
        # token_hash : SHA-256 of raw token — raw value never stored
        # user_id    : FK to users, cascade delete revokes all sessions on user removal
        # expires_at : checked on every refresh attempt
        # created_at : useful for audit and anomaly detection
        await conn.execute("""
            CREATE TABLE IF NOT EXISTS refresh_tokens (
                token_hash  TEXT        PRIMARY KEY,
                user_id     UUID        NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                expires_at  TIMESTAMPTZ NOT NULL,
                created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

